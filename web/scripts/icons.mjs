// Collects every Material Symbols name used in src/ so the icon font can be
// loaded as a small subset. Writes src/lib/icons.ts.
import fs from 'node:fs';
import path from 'node:path';

const valid = new Set(JSON.parse(fs.readFileSync('scripts/material-symbols-names.json', 'utf8')));
const names = new Set(['menu', 'close', 'search', 'dark_mode', 'light_mode']);
const patterns = [
  /<Icon[^>]*?\sname="([a-z0-9_]+)"/g,
  /\bicon[:=]\s*\{?\s*['"]([a-z0-9_]+)['"]/g,
  /\bic\(\s*'([a-z0-9_]+)'/g,
  /class="ms[^"]*">([a-z0-9_]+)</g,
  /ICON\s*\(\s*'([a-z0-9_]+)'/g,
  /\/\*icons\*\/\s*\[([^\]]+)\]/g,
  // Any quoted literal that is a real icon name (icon maps, data tables).
  /['"]([a-z][a-z0-9_]{2,})['"]/g,
  // Ligature text inside a .ms element.
  /class="ms[^"]*"[^>]*>([a-z0-9_]+)</g,
];
function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.(astro|ts|js|mjs)$/.test(e.name) && !p.endsWith('icons.ts')) {
      const src = fs.readFileSync(p, 'utf8');
      for (const re of patterns) {
        for (const m of src.matchAll(re)) {
          if (re.source.startsWith('\\/\\*icons')) {
            for (const n of m[1].matchAll(/'([a-z0-9_]+)'/g)) names.add(n[1]);
          } else names.add(m[1]);
        }
      }
    }
  }
}
walk('src');
const bad = [...names].filter((n) => !valid.has(n));
const list = [...names].filter((n) => valid.has(n)).sort();
if (bad.length) console.log('icons: not real icon names (ignored):', bad.filter((n) => n.length > 2).slice(0, 40).join(', '));
fs.writeFileSync('src/lib/icons.ts', `// Generated by scripts/icons.mjs — do not edit.\nexport const ICONS = ${JSON.stringify(list)};\n`);
console.log(`icons: ${list.length}`);
